def norm(s):
    s=s.strip()
    s=s.replace('الصالحجين','الصالحين')
    s=re.sub(r'(?<=[ء-ي])6','ئ',s)
    m=re.match(r'^([.،])\s*(.*)$',s)
    if m: s=m.group(2)+m.group(1)
    s=s.replace(' ,',',')
    return s
