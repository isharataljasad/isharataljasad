import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const root=new URL('../',import.meta.url);
const read=p=>readFileSync(new URL(p,root),'utf8');
const inv=JSON.parse(read('chemistry/goldwhite-inventory.json'));
const old=JSON.parse(read('chemistry/educator-inventory.json'));
const scope=JSON.parse(read('chemistry/scope.json'));
const html=read('chemistry/index.html');
const arena=read('chemistry/atomic/index.html');
const engine=read('chemistry/atomic/engine.js');
assert.equal(inv.source_id,'EDU_GOLDWHITE');
assert.equal(inv.status,'SOURCE_INVENTORY_NOT_SYLLABUS');
assert.equal(inv.access,'PRIVATE_SUBSCRIBER_SOURCE');
assert.equal(inv.lessons.length,35);
assert.deepEqual(inv.lessons.map(x=>x.n),Array.from({length:35},(_,i)=>i+1));
assert.equal(new Set(inv.lessons.map(x=>x.title)).size,35);
assert.equal(old.lessons.length,24);
assert.equal(scope.arena_targets.length,9);
const ids=new Set(scope.arena_targets.map(x=>x.id));
const valid=new Set(['DIRECT_CANDIDATE','SUPPORT_CANDIDATE','PREREQUISITE','DEFERRED']);
for(const lesson of inv.lessons){
 assert.match(lesson.duration,/^\d{2}:\d{2}$/);
 assert.ok(valid.has(lesson.fit),`invalid fit ${lesson.n}`);
 assert.ok(lesson.title.length>5 && lesson.focus.length>15);
 assert.ok(lesson.arenas.every(a=>ids.has(a)),`unknown arena ${lesson.n}`);
 assert.equal(lesson.fit==='DEFERRED'&&lesson.arenas.length!==0,false,`deferred lesson promoted ${lesson.n}`);
 assert.equal('transcript' in lesson,false,'never publish transcript text');
 assert.equal('video_url' in lesson,false,'no fabricated lesson urls');
}
assert.ok(inv.lessons.find(x=>x.n===3).arenas.includes('A1'));
assert.ok(inv.lessons.find(x=>x.n===30).arenas.includes('A9'));
assert.ok(inv.lessons.find(x=>x.n===31).arenas.includes('A9'));
for(const label of ['General Chemistry with Franklin Ow','Professor Goldwhite','مسار الكتب','Pearson+','Exam DNA','Topic → Arena','/chemistry/atomic/','goldwhite-inventory.json']) assert.ok(html.includes(label),`missing ${label}`);
assert.match(html,/<html lang="ar" dir="rtl">/);
assert.match(arena,/<script src="\.\/engine\.js" defer><\/script>/);
assert.ok(arena.includes('أسئلة أصلية'));
assert.ok(arena.includes('ليس') || arena.includes('وليست'));
assert.ok(!html.includes('.srt</a>')&&!arena.includes('.srt</a>'));
new Function(engine);
for(const term of ['navigator.clipboard.writeText','localStorage','s.phase=\'remediate\'','s.phase=\'passed\'','s.phase=\'needs_review\'']) assert.ok(engine.includes(term),`missing ${term}`);
assert.ok(!engine.includes('intelligence score'));
console.log('PASS Chemistry: 35 Goldwhite + 24 Franklin independent lessons, 9 scoped Arenas, interactive auto-graded atomic challenge, private content excluded.');
